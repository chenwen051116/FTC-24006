    public double getdisAuto() {
        drive.setPose(follower.pose());
        double heading = follower.pose().heading();
        double realx =  follower.pose().x();
        double realy =  follower.pose().y();
        if (heading > 0) {
            realx -= shooterCenterDis * cos(heading);
            realy -= shooterCenterDis * sin(heading);
        } else {
            heading = abs(heading);
            realx -= shooterCenterDis * cos(heading);
            realy += shooterCenterDis * sin(heading);
        }
        double x = realx - drive.aimX();
        double y = realy - drive.aimY();
        return sqrt(x * x + y * y);
    }
    public double getdis3DAuto() {
        double d = getdisAuto();
        return sqrt(d * d + aimHeightIn * aimHeightIn);
    }
